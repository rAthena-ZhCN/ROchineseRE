		for ScrollItemID, info in pairs(tblLapineDdukddakBox.sources) do
			result, msg = registerLapineDdukddakBoxSourceInfo(info.SourceItems, info.NeedRefineMax, info.NeedRefineMin, info.NeedCount, ScrollItemID)
			if not(result) then
				return false, msg
			end
		end
		for ScrollItemID, info in pairs(tblLapineDdukddakBox.results) do
			result, msg = registerLapineDdukddakBoxResultInfo(info.ResultItems, info.RefineProbability, info.RandomOptionCode, ScrollItemID)
			if not(result) then
				return false, msg
			end
